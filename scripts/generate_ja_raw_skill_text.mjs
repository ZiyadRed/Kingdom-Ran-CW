import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readdirSync } from 'node:fs'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'))

// Every runtime dataset that can ask for an original Japanese skill by textId.
export const TEXT_ID_SOURCES = [
  ...readdirSync(resolve(root, 'data/characters')).filter(file => file.endsWith('.json')).map(file => `data/characters/${file}`),
  'data/souha_role_skills.json',
  'data/cw6_scene_cards.json',
  'data/scene_card_cw_buffs.json',
]

export function collectTextIds(value, ids = new Set()) {
  if (Array.isArray(value)) value.forEach(item => collectTextIds(item, ids))
  else if (value && typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) {
      if (key === 'textId' && Number.isInteger(child)) ids.add(child)
      else collectTextIds(child, ids)
    }
  }
  return ids
}

// The raw STBL tables are ~220 KB, but the client only needs the rows that
// some general, role skill or scene card references. This projection keeps the
// exact raw strings for those rows so every page stops shipping both tables.
export function deriveJaRawSkillText() {
  const names = read('data/source/ja/skill_name.raw.json').values || []
  const descs = read('data/source/ja/skill_desc.raw.json').values || []
  const ids = new Set()
  for (const path of TEXT_ID_SOURCES) collectTextIds(read(path), ids)
  const rows = {}
  for (const id of [...ids].sort((a, b) => a - b)) {
    if (typeof names[id] === 'string' && names[id]) rows[id] = [names[id], descs[id] || '']
  }
  return rows
}

export function generateJaRawSkillText() {
  const rows = deriveJaRawSkillText()
  const output = resolve(root, 'src/generated/ja-raw-skill-text.js')
  const content = '// Generated by scripts/generate_ja_raw_skill_text.mjs from data/source/ja/*.raw.json. Do not edit.\n'
    + 'export default ' + JSON.stringify(rows) + '\n'
  mkdirSync(dirname(output), { recursive: true })
  let previous = ''
  try { previous = readFileSync(output, 'utf8') } catch { /* first generation */ }
  if (previous !== content) writeFileSync(output, content)
  console.log(`generate_ja_raw_skill_text: ${Object.keys(rows).length} referenced raw skill rows`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateJaRawSkillText()
